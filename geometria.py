# calculadora.py

def sumar(a, b):
    return a + b

def restar(a, b):
    return a - b

def multiplicar(a, b):
    return a * b

if __name__ == "__main__":
    print("Calculadora simple")
    print("2 + 3 =", sumar(2, 3))
    print("10 - 4 =", restar(10, 4))
    print("4 * 5 =", multiplicar(4, 5))
